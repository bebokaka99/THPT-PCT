CREATE OR REPLACE FUNCTION validate_assessment_configuration_scope()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  semester_year_id BIGINT;
  curriculum_exists BOOLEAN;
BEGIN
  SELECT academic_year_id
  INTO semester_year_id
  FROM semesters
  WHERE id = NEW.semester_id;

  SELECT EXISTS (
    SELECT 1
    FROM curriculum_subjects curriculum
    JOIN subjects subject ON subject.id = curriculum.subject_id
    WHERE curriculum.academic_year_id = semester_year_id
      AND curriculum.grade_level = NEW.grade_level
      AND curriculum.subject_id = NEW.subject_id
      AND curriculum.is_active = TRUE
      AND subject.is_active = TRUE
  )
  INTO curriculum_exists;

  IF semester_year_id IS NULL THEN
    RAISE EXCEPTION 'Assessment configuration semester does not exist';
  END IF;
  IF NOT curriculum_exists THEN
    RAISE EXCEPTION
      'Assessment configuration subject is not active in the curriculum';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_assessment_configuration_scope
BEFORE INSERT OR UPDATE OF subject_id, semester_id, grade_level
ON assessment_configurations
FOR EACH ROW EXECUTE FUNCTION validate_assessment_configuration_scope();

CREATE OR REPLACE FUNCTION protect_assessment_configuration_history()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.subject_id <> OLD.subject_id
    OR NEW.semester_id <> OLD.semester_id
    OR NEW.grade_level <> OLD.grade_level
    OR NEW.version <> OLD.version
  THEN
    RAISE EXCEPTION
      'Assessment configuration identity is immutable; create a new version';
  END IF;

  IF OLD.status <> 'draft' AND (
    NEW.title <> OLD.title
    OR NEW.score_scale <> OLD.score_scale
    OR NEW.decimal_places <> OLD.decimal_places
    OR NEW.rounding_mode <> OLD.rounding_mode
  ) THEN
    RAISE EXCEPTION
      'Published assessment configuration content is immutable';
  END IF;

  IF OLD.status = 'archived' AND NEW.status <> 'archived' THEN
    RAISE EXCEPTION
      'Archived assessment configuration cannot be reactivated';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_protect_assessment_configuration_history
BEFORE UPDATE ON assessment_configurations
FOR EACH ROW EXECUTE FUNCTION protect_assessment_configuration_history();

CREATE OR REPLACE FUNCTION ensure_assessment_category_is_writable()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  target_configuration_id BIGINT;
  configuration_status assessment_configuration_status;
BEGIN
  target_configuration_id := COALESCE(NEW.configuration_id, OLD.configuration_id);

  SELECT status
  INTO configuration_status
  FROM assessment_configurations
  WHERE id = target_configuration_id;

  IF configuration_status IS NOT NULL AND configuration_status <> 'draft' THEN
    RAISE EXCEPTION
      'Assessment categories are immutable after configuration activation';
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_assessment_category_writable
BEFORE INSERT OR UPDATE OR DELETE ON assessment_categories
FOR EACH ROW EXECUTE FUNCTION ensure_assessment_category_is_writable();

CREATE OR REPLACE FUNCTION validate_assessment_category_weights()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  target_configuration_id BIGINT;
  category_count INTEGER;
  total_weight NUMERIC(7, 2);
BEGIN
  target_configuration_id := COALESCE(NEW.configuration_id, OLD.configuration_id);

  IF NOT EXISTS (
    SELECT 1 FROM assessment_configurations
    WHERE id = target_configuration_id
  ) THEN
    RETURN NULL;
  END IF;

  SELECT COUNT(*), COALESCE(SUM(weight_percent), 0)
  INTO category_count, total_weight
  FROM assessment_categories
  WHERE configuration_id = target_configuration_id;

  IF category_count = 0 OR total_weight <> 100.00 THEN
    RAISE EXCEPTION
      'Assessment category weights must total exactly 100 percent';
  END IF;

  RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_assessment_category_weight_total
AFTER INSERT OR UPDATE OR DELETE ON assessment_categories
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION validate_assessment_category_weights();
