DO $$
BEGIN
  CREATE TYPE assessment_configuration_status AS ENUM (
    'draft',
    'active',
    'archived'
  );
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$
BEGIN
  CREATE TYPE assessment_rounding_mode AS ENUM (
    'half_up',
    'half_even',
    'truncate'
  );
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE assessment_configurations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE RESTRICT,
  semester_id BIGINT NOT NULL REFERENCES semesters(id) ON DELETE RESTRICT,
  grade_level INTEGER NOT NULL CHECK (grade_level BETWEEN 10 AND 12),
  version INTEGER NOT NULL CHECK (version > 0),
  title VARCHAR(255) NOT NULL,
  score_scale NUMERIC(6, 2) NOT NULL DEFAULT 10
    CHECK (score_scale > 0 AND score_scale <= 100),
  decimal_places SMALLINT NOT NULL DEFAULT 1
    CHECK (decimal_places BETWEEN 0 AND 2),
  rounding_mode assessment_rounding_mode NOT NULL DEFAULT 'half_up',
  status assessment_configuration_status NOT NULL DEFAULT 'draft',
  created_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  activated_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (subject_id, semester_id, grade_level, version),
  CHECK (
    (status = 'active' AND activated_at IS NOT NULL)
    OR status <> 'active'
  )
);

CREATE TABLE assessment_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  configuration_id BIGINT NOT NULL
    REFERENCES assessment_configurations(id) ON DELETE CASCADE,
  code VARCHAR(50) NOT NULL,
  name VARCHAR(150) NOT NULL,
  weight_percent NUMERIC(5, 2) NOT NULL
    CHECK (weight_percent > 0 AND weight_percent <= 100),
  coefficient NUMERIC(5, 2) NOT NULL DEFAULT 1
    CHECK (coefficient > 0 AND coefficient <= 20),
  max_entries SMALLINT NOT NULL DEFAULT 1
    CHECK (max_entries BETWEEN 1 AND 20),
  score_scale NUMERIC(6, 2) NOT NULL DEFAULT 10
    CHECK (score_scale > 0 AND score_scale <= 100),
  sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (configuration_id, code)
);

CREATE UNIQUE INDEX uq_assessment_configurations_active_scope
  ON assessment_configurations(subject_id, semester_id, grade_level)
  WHERE status = 'active';

CREATE UNIQUE INDEX uq_assessment_configurations_draft_scope
  ON assessment_configurations(subject_id, semester_id, grade_level)
  WHERE status = 'draft';

CREATE INDEX idx_assessment_configurations_scope_status
  ON assessment_configurations(
    semester_id,
    grade_level,
    subject_id,
    status,
    version DESC
  );

CREATE INDEX idx_assessment_categories_configuration_order
  ON assessment_categories(configuration_id, sort_order, id);

