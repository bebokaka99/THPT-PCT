CREATE INDEX idx_timetables_classroom_active ON timetables (classroom_id, is_active, updated_at DESC);
CREATE INDEX idx_timetable_items_day_lesson ON timetable_items (day_of_week, lesson_index);

DO $$
DECLARE
  table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'users', 'roles', 'permissions', 'categories', 'posts', 'post_images',
    'documents', 'events', 'imported_contents', 'teacher_profiles',
    'student_profiles', 'classrooms', 'classroom_posts', 'classroom_documents',
    'timetables'
  ]
  LOOP
    EXECUTE format(
      'CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
      'trg_' || table_name || '_updated_at',
      table_name
    );
  END LOOP;
END $$;
