CREATE INDEX idx_classroom_posts_classroom_status ON classroom_posts (classroom_id, status);
CREATE INDEX idx_classroom_documents_classroom_status ON classroom_documents (classroom_id, status);
CREATE INDEX idx_notifications_target_role_created_at ON notifications (target_role, created_at DESC);
CREATE INDEX idx_notifications_classroom_created_at ON notifications (classroom_id, created_at DESC);
