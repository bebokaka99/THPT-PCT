CREATE EXTENSION IF NOT EXISTS unaccent;

CREATE TABLE subjects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  subject_group VARCHAR(80) NOT NULL DEFAULT 'other',
  description TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (code ~ '^[A-Z0-9_]{2,30}$')
);

CREATE TABLE curriculum_subjects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_year_id BIGINT NOT NULL
    REFERENCES academic_years(id) ON DELETE RESTRICT,
  subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE RESTRICT,
  grade_level INTEGER NOT NULL CHECK (grade_level BETWEEN 10 AND 12),
  periods_per_week NUMERIC(4,1) NOT NULL CHECK (periods_per_week > 0),
  is_required BOOLEAN NOT NULL DEFAULT TRUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (academic_year_id, subject_id, grade_level)
);

CREATE INDEX idx_subjects_active_group
  ON subjects(is_active, subject_group, name);

CREATE INDEX idx_curriculum_year_grade_active
  ON curriculum_subjects(academic_year_id, grade_level, is_active);

CREATE TRIGGER trg_subjects_updated_at
BEFORE UPDATE ON subjects
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_curriculum_subjects_updated_at
BEFORE UPDATE ON curriculum_subjects
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE timetable_items
  ADD COLUMN subject_id BIGINT REFERENCES subjects(id) ON DELETE RESTRICT;

CREATE INDEX idx_timetable_items_subject
  ON timetable_items(subject_id);

