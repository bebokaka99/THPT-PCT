WITH unmatched AS (
  SELECT
    lower(unaccent(btrim(subject_name))) AS normalized_name,
    MIN(btrim(subject_name)) AS display_name
  FROM timetable_items
  WHERE subject_id IS NULL
    AND btrim(subject_name) <> ''
  GROUP BY lower(unaccent(btrim(subject_name)))
)
