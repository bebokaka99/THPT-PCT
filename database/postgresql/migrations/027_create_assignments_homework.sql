CREATE TRIGGER trg_assignment_submissions_updated_at
BEFORE UPDATE ON assignment_submissions
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE OR REPLACE FUNCTION validate_assignment_scope()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  assignment_matches BOOLEAN;
  semester_start DATE;
  semester_end DATE;
BEGIN
  SELECT EXISTS (
    SELECT 1
    FROM teaching_assignments teaching
    WHERE teaching.id = NEW.teaching_assignment_id
      AND teaching.classroom_id = NEW.classroom_id
      AND teaching.subject_id = NEW.subject_id
      AND teaching.semester_id = NEW.semester_id
  )
  INTO assignment_matches;

  SELECT start_date, end_date
  INTO semester_start, semester_end
  FROM semesters
  WHERE id = NEW.semester_id;

  IF NOT assignment_matches THEN
    RAISE EXCEPTION 'Assignment scope must match teaching assignment';
  END IF;
  IF NEW.due_at::DATE < semester_start OR NEW.due_at::DATE > semester_end THEN
    RAISE EXCEPTION 'Assignment due date must be inside the semester';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_assignment_scope
BEFORE INSERT OR UPDATE OF classroom_id, subject_id, semester_id,
  teaching_assignment_id, due_at
ON assignments
FOR EACH ROW EXECUTE FUNCTION validate_assignment_scope();
