CREATE OR REPLACE FUNCTION validate_timetable_item_assignment()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  timetable_classroom_id BIGINT;
  timetable_semester_id BIGINT;
  assignment_teacher_id BIGINT;
  assignment_classroom_id BIGINT;
  assignment_subject_id BIGINT;
  assignment_semester_id BIGINT;
  assignment_status teaching_assignment_status;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM bell_periods
    WHERE shift_id = NEW.shift_id AND period_index = NEW.lesson_index
  ) THEN
    RAISE EXCEPTION 'TIMETABLE_INVALID_PERIOD: shift % does not contain period %',
      NEW.shift_id, NEW.lesson_index;
  END IF;

  IF NEW.teaching_assignment_id IS NULL THEN
    NEW.teacher_user_id = NULL;
    RETURN NEW;
  END IF;

  SELECT classroom_id, semester_id
  INTO timetable_classroom_id, timetable_semester_id
  FROM timetables WHERE id = NEW.timetable_id;

  SELECT teacher_user_id, classroom_id, subject_id, semester_id, status
  INTO assignment_teacher_id, assignment_classroom_id, assignment_subject_id,
    assignment_semester_id, assignment_status
  FROM teaching_assignments WHERE id = NEW.teaching_assignment_id;

  IF assignment_teacher_id IS NULL
    OR assignment_status <> 'active'
    OR assignment_classroom_id <> timetable_classroom_id
    OR assignment_semester_id IS DISTINCT FROM timetable_semester_id
    OR assignment_subject_id IS DISTINCT FROM NEW.subject_id
  THEN
    RAISE EXCEPTION 'TIMETABLE_INVALID_ASSIGNMENT: assignment does not match class, semester, and subject';
  END IF;

  NEW.teacher_user_id = assignment_teacher_id;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_timetable_item_assignment
BEFORE INSERT OR UPDATE ON timetable_items
FOR EACH ROW EXECUTE FUNCTION validate_timetable_item_assignment();

CREATE OR REPLACE FUNCTION validate_timetable_publish()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  conflicting RECORD;
BEGIN
  IF NEW.status <> 'published' THEN
    NEW.is_active = FALSE;
    IF NEW.status = 'archived' THEN
      NEW.published_at = COALESCE(NEW.published_at, OLD.published_at);
    END IF;
    RETURN NEW;
  END IF;

  IF EXISTS (
    SELECT 1 FROM timetable_items
    WHERE timetable_id = NEW.id
      AND (teaching_assignment_id IS NULL OR teacher_user_id IS NULL)
  ) THEN
    RAISE EXCEPTION 'TIMETABLE_ASSIGNMENT_REQUIRED: every published lesson needs a teaching assignment';
  END IF;

  SELECT
    current_item.day_of_week,
    current_item.lesson_index,
    shift.name AS shift_name,
    teacher.full_name AS teacher_name,
    current_item.room,
    classroom.name AS classroom_name
  INTO conflicting
  FROM timetable_items current_item
  JOIN school_shifts shift ON shift.id = current_item.shift_id
  LEFT JOIN users teacher ON teacher.id = current_item.teacher_user_id
  JOIN timetable_items other_item
    ON other_item.day_of_week = current_item.day_of_week
    AND other_item.shift_id = current_item.shift_id
    AND other_item.lesson_index = current_item.lesson_index
    AND (
      other_item.teacher_user_id = current_item.teacher_user_id
      OR (
        NULLIF(lower(btrim(other_item.room)), '') IS NOT NULL
        AND lower(btrim(other_item.room)) = lower(btrim(current_item.room))
      )
    )
  JOIN timetables other_timetable
    ON other_timetable.id = other_item.timetable_id
    AND other_timetable.id <> NEW.id
    AND other_timetable.status = 'published'
    AND other_timetable.semester_id IS NOT DISTINCT FROM NEW.semester_id
  JOIN classrooms classroom ON classroom.id = other_timetable.classroom_id
  WHERE current_item.timetable_id = NEW.id
  LIMIT 1;

  IF conflicting IS NOT NULL THEN
    RAISE EXCEPTION
      'TIMETABLE_CONFLICT: day %, %, period %, teacher %, room %, class %',
      conflicting.day_of_week,
      conflicting.shift_name,
      conflicting.lesson_index,
      COALESCE(conflicting.teacher_name, '-'),
      COALESCE(conflicting.room, '-'),
      conflicting.classroom_name;
  END IF;

  NEW.is_active = TRUE;
  NEW.published_at = COALESCE(NEW.published_at, CURRENT_TIMESTAMP);
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_timetable_publish
BEFORE INSERT OR UPDATE OF status ON timetables
FOR EACH ROW EXECUTE FUNCTION validate_timetable_publish();
