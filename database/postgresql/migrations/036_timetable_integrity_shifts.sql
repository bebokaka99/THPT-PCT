WITH versions AS (
  SELECT id,
    ROW_NUMBER() OVER (
      PARTITION BY classroom_id, COALESCE(semester_id, 0)
      ORDER BY created_at, id
    ) AS version_number
  FROM timetables
)
UPDATE timetables timetable
SET version_number = versions.version_number
FROM versions
WHERE versions.id = timetable.id;

