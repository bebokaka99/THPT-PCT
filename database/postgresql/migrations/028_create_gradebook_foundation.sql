CREATE TABLE gradebooks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teaching_assignment_id BIGINT NOT NULL UNIQUE
    REFERENCES teaching_assignments(id) ON DELETE RESTRICT,
  assessment_configuration_id BIGINT NOT NULL
    REFERENCES assessment_configurations(id) ON DELETE RESTRICT,
  classroom_id BIGINT NOT NULL REFERENCES classrooms(id) ON DELETE RESTRICT,
  subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE RESTRICT,
  semester_id BIGINT NOT NULL REFERENCES semesters(id) ON DELETE RESTRICT,
  status gradebook_status NOT NULL DEFAULT 'draft',
  revision INTEGER NOT NULL DEFAULT 1 CHECK (revision > 0),
  created_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE gradebook_columns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gradebook_id BIGINT NOT NULL REFERENCES gradebooks(id) ON DELETE CASCADE,
  assessment_category_id BIGINT NOT NULL
    REFERENCES assessment_categories(id) ON DELETE RESTRICT,
  category_code VARCHAR(50) NOT NULL,
  category_name VARCHAR(150) NOT NULL,
  entry_index SMALLINT NOT NULL CHECK (entry_index > 0),
  label VARCHAR(150) NOT NULL,
  max_score NUMERIC(6, 2) NOT NULL CHECK (max_score > 0),
  weight_percent NUMERIC(5, 2) NOT NULL
    CHECK (weight_percent > 0 AND weight_percent <= 100),
  sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (gradebook_id, assessment_category_id, entry_index)
);

CREATE TABLE student_scores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gradebook_id BIGINT NOT NULL REFERENCES gradebooks(id) ON DELETE RESTRICT,
  column_id BIGINT NOT NULL REFERENCES gradebook_columns(id) ON DELETE RESTRICT,
  student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  state grade_score_state NOT NULL DEFAULT 'scored',
  score NUMERIC(6, 2),
  version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
  updated_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (gradebook_id, column_id, student_user_id),
  CHECK (
    (state = 'scored' AND score IS NOT NULL AND score >= 0)
    OR (state IN ('absent', 'exempt') AND score IS NULL)
  )
);

CREATE TABLE student_score_audits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_score_id BIGINT REFERENCES student_scores(id) ON DELETE SET NULL,
  gradebook_id BIGINT NOT NULL REFERENCES gradebooks(id) ON DELETE RESTRICT,
  column_id BIGINT NOT NULL REFERENCES gradebook_columns(id) ON DELETE RESTRICT,
  student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  action VARCHAR(20) NOT NULL CHECK (action IN ('insert', 'update')),
  old_state grade_score_state,
  new_state grade_score_state NOT NULL,
  old_score NUMERIC(6, 2),
  new_score NUMERIC(6, 2),
  old_version INTEGER,
  new_version INTEGER NOT NULL,
  reason VARCHAR(500),
  changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_gradebooks_scope
