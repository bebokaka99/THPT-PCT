CREATE OR REPLACE FUNCTION validate_gradebook_scope()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  assignment_record teaching_assignments%ROWTYPE;
  configuration_record assessment_configurations%ROWTYPE;
  classroom_grade INTEGER;
BEGIN
  SELECT * INTO assignment_record
  FROM teaching_assignments
  WHERE id = NEW.teaching_assignment_id;

  SELECT * INTO configuration_record
  FROM assessment_configurations
  WHERE id = NEW.assessment_configuration_id;

  SELECT grade_level INTO classroom_grade
  FROM classrooms
  WHERE id = NEW.classroom_id;

  IF assignment_record.id IS NULL OR assignment_record.status <> 'active' THEN
    RAISE EXCEPTION 'Gradebook requires an active teaching assignment';
  END IF;
  IF configuration_record.id IS NULL
    OR configuration_record.status <> 'active'
  THEN
    RAISE EXCEPTION 'Gradebook requires an active assessment configuration';
  END IF;
  IF assignment_record.classroom_id <> NEW.classroom_id
    OR assignment_record.subject_id <> NEW.subject_id
    OR assignment_record.semester_id <> NEW.semester_id
  THEN
    RAISE EXCEPTION 'Gradebook scope does not match teaching assignment';
  END IF;
  IF configuration_record.subject_id <> NEW.subject_id
    OR configuration_record.semester_id <> NEW.semester_id
    OR configuration_record.grade_level <> classroom_grade
  THEN
    RAISE EXCEPTION 'Assessment configuration does not match gradebook scope';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_gradebook_scope
BEFORE INSERT OR UPDATE ON gradebooks
FOR EACH ROW EXECUTE FUNCTION validate_gradebook_scope();

CREATE OR REPLACE FUNCTION protect_gradebook_identity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.teaching_assignment_id <> OLD.teaching_assignment_id
    OR NEW.assessment_configuration_id <> OLD.assessment_configuration_id
    OR NEW.classroom_id <> OLD.classroom_id
    OR NEW.subject_id <> OLD.subject_id
    OR NEW.semester_id <> OLD.semester_id
  THEN
    RAISE EXCEPTION 'Gradebook identity is immutable';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_protect_gradebook_identity
BEFORE UPDATE ON gradebooks
FOR EACH ROW EXECUTE FUNCTION protect_gradebook_identity();

CREATE OR REPLACE FUNCTION validate_student_score_scope()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  target_classroom_id BIGINT;
  target_semester_id BIGINT;
  semester_start DATE;
  semester_end DATE;
  column_matches BOOLEAN;
  student_matches BOOLEAN;
BEGIN
  SELECT classroom_id, semester_id
  INTO target_classroom_id, target_semester_id
  FROM gradebooks
  WHERE id = NEW.gradebook_id;

  SELECT start_date, end_date
  INTO semester_start, semester_end
  FROM semesters
  WHERE id = target_semester_id;

  SELECT EXISTS (
    SELECT 1 FROM gradebook_columns
    WHERE id = NEW.column_id AND gradebook_id = NEW.gradebook_id
  ) INTO column_matches;

  SELECT EXISTS (
    SELECT 1
    FROM student_enrollments enrollment
    JOIN users student ON student.id = enrollment.student_user_id
    WHERE enrollment.student_user_id = NEW.student_user_id
      AND enrollment.classroom_id = target_classroom_id
      AND enrollment.enrolled_at <= semester_end
      AND (
        enrollment.ended_at IS NULL
        OR enrollment.ended_at >= semester_start
      )
      AND student.status = 'active'
  ) INTO student_matches;

  IF NOT column_matches THEN
    RAISE EXCEPTION 'Score column does not belong to gradebook';
  END IF;
  IF NOT student_matches THEN
    RAISE EXCEPTION 'Student is not enrolled in gradebook classroom';
  END IF;

  IF NEW.state = 'scored' AND NEW.score > (
    SELECT max_score FROM gradebook_columns WHERE id = NEW.column_id
  ) THEN
    RAISE EXCEPTION 'Score exceeds column maximum';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_student_score_scope
BEFORE INSERT OR UPDATE ON student_scores
FOR EACH ROW EXECUTE FUNCTION validate_student_score_scope();

CREATE OR REPLACE FUNCTION round_half_even(
  input_value NUMERIC,
  decimal_places INTEGER
)
RETURNS NUMERIC
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  factor NUMERIC := power(10::NUMERIC, decimal_places);
  scaled NUMERIC := input_value * factor;
  lower_value NUMERIC := floor(scaled);
  fraction NUMERIC := scaled - lower_value;
  rounded_value NUMERIC;
BEGIN
  IF fraction = 0.5 THEN
    rounded_value := CASE
      WHEN mod(lower_value, 2) = 0 THEN lower_value
      ELSE lower_value + 1
    END;
  ELSE
    rounded_value := round(scaled);
  END IF;
  RETURN rounded_value / factor;
END;
$$;
