DO $$
BEGIN
  CREATE TYPE student_enrollment_status AS ENUM (
    'active',
    'transferred',
    'reserved',
    'withdrawn',
    'graduated'
  );
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE student_enrollments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  classroom_id BIGINT NOT NULL REFERENCES classrooms(id) ON DELETE RESTRICT,
  academic_year_id BIGINT NOT NULL REFERENCES academic_years(id) ON DELETE RESTRICT,
  status student_enrollment_status NOT NULL DEFAULT 'active',
  enrolled_at DATE NOT NULL DEFAULT CURRENT_DATE,
  ended_at DATE,
  previous_enrollment_id BIGINT REFERENCES student_enrollments(id) ON DELETE SET NULL,
  note TEXT,
  created_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (
    (status = 'active' AND ended_at IS NULL)
    OR
    (status <> 'active' AND ended_at IS NOT NULL)
  ),
  CHECK (ended_at IS NULL OR ended_at >= enrolled_at)
);

CREATE INDEX idx_student_enrollments_student_history
  ON student_enrollments(student_user_id, academic_year_id, created_at DESC);

CREATE INDEX idx_student_enrollments_classroom_status
  ON student_enrollments(classroom_id, status);

CREATE INDEX idx_student_enrollments_academic_year_status
  ON student_enrollments(academic_year_id, status);

CREATE UNIQUE INDEX uq_student_enrollments_one_active_per_year
  ON student_enrollments(student_user_id, academic_year_id)
  WHERE status = 'active';

CREATE TRIGGER trg_student_enrollments_updated_at
BEFORE UPDATE ON student_enrollments
