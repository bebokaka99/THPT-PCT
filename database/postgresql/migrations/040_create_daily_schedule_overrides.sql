CREATE OR REPLACE FUNCTION validate_daily_schedule_override_scope()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  timetable_classroom_id BIGINT;
  timetable_status_value timetable_status;
  item_teacher_id BIGINT;
  item_subject_id BIGINT;
  item_semester_id BIGINT;
  substitute_is_teacher BOOLEAN;
  substitute_has_assignment BOOLEAN;
BEGIN
  SELECT timetable.classroom_id, timetable.status, item.teacher_user_id,
    item.subject_id, timetable.semester_id
  INTO timetable_classroom_id, timetable_status_value, item_teacher_id,
    item_subject_id, item_semester_id
  FROM timetable_items item
  JOIN timetables timetable ON timetable.id = item.timetable_id
  WHERE item.id = NEW.timetable_item_id AND timetable.id = NEW.timetable_id;

  IF timetable_classroom_id IS NULL OR timetable_classroom_id <> NEW.classroom_id THEN
    RAISE EXCEPTION 'DAILY_OVERRIDE_INVALID_TIMETABLE_ITEM: item does not belong to timetable/classroom';
  END IF;
  IF timetable_status_value <> 'published' THEN
    RAISE EXCEPTION 'DAILY_OVERRIDE_TIMETABLE_NOT_PUBLISHED: only published timetable slots can be overridden';
  END IF;

  IF NEW.substitute_teacher_user_id IS NOT NULL THEN
    SELECT EXISTS (
      SELECT 1 FROM user_roles ur JOIN roles role ON role.id = ur.role_id
      JOIN users account ON account.id = ur.user_id
      WHERE ur.user_id = NEW.substitute_teacher_user_id
        AND role.name = 'teacher' AND account.status = 'active'
    ) INTO substitute_is_teacher;
    IF NOT substitute_is_teacher THEN
      RAISE EXCEPTION 'DAILY_OVERRIDE_SUBSTITUTE_NOT_TEACHER: substitute account is not an active teacher';
    END IF;
    IF item_subject_id IS NOT NULL AND item_semester_id IS NOT NULL THEN
      SELECT EXISTS (
        SELECT 1 FROM teaching_assignments assignment
        WHERE assignment.teacher_user_id = NEW.substitute_teacher_user_id
          AND assignment.classroom_id = NEW.classroom_id
          AND assignment.subject_id = item_subject_id
          AND assignment.semester_id = item_semester_id
          AND assignment.status = 'active'
      ) INTO substitute_has_assignment;
      IF NOT substitute_has_assignment THEN
        RAISE EXCEPTION 'DAILY_OVERRIDE_SUBSTITUTE_ASSIGNMENT_REQUIRED: substitute has no active assignment for class and subject';
      END IF;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_daily_schedule_override_scope
BEFORE INSERT OR UPDATE ON daily_schedule_overrides
FOR EACH ROW EXECUTE FUNCTION validate_daily_schedule_override_scope();
