CREATE TABLE teaching_assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  classroom_id BIGINT NOT NULL REFERENCES classrooms(id) ON DELETE RESTRICT,
  subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE RESTRICT,
  semester_id BIGINT NOT NULL REFERENCES semesters(id) ON DELETE RESTRICT,
  role teaching_assignment_role NOT NULL DEFAULT 'primary',
  status teaching_assignment_status NOT NULL DEFAULT 'active',
  assigned_at DATE NOT NULL,
  ended_at DATE,
  note TEXT,
  created_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (
    (status = 'active' AND ended_at IS NULL)
    OR
    (status = 'inactive' AND ended_at IS NOT NULL)
  ),
  CHECK (ended_at IS NULL OR ended_at >= assigned_at)
);

CREATE UNIQUE INDEX uq_teaching_assignments_active_exact
  ON teaching_assignments(
    teacher_user_id,
    classroom_id,
    subject_id,
    semester_id
  )
  WHERE status = 'active';

CREATE INDEX idx_teaching_assignments_teacher_period
  ON teaching_assignments(teacher_user_id, semester_id, status);

CREATE INDEX idx_teaching_assignments_class_subject
  ON teaching_assignments(classroom_id, subject_id, semester_id, status);

