CREATE OR REPLACE FUNCTION validate_attendance_session_scope()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  classroom_year_id BIGINT;
  semester_year_id BIGINT;
  semester_start DATE;
  semester_end DATE;
  assignment_matches BOOLEAN;
BEGIN
  SELECT academic_year_id
  INTO classroom_year_id
  FROM classrooms
  WHERE id = NEW.classroom_id;

  SELECT academic_year_id, start_date, end_date
  INTO semester_year_id, semester_start, semester_end
  FROM semesters
  WHERE id = NEW.semester_id;

  IF classroom_year_id IS NULL OR semester_year_id <> classroom_year_id THEN
    RAISE EXCEPTION 'Attendance semester must belong to the classroom academic year';
  END IF;
  IF NEW.session_date < semester_start OR NEW.session_date > semester_end THEN
    RAISE EXCEPTION 'Attendance date must be inside the semester';
  END IF;

  IF NEW.teaching_assignment_id IS NOT NULL THEN
    SELECT EXISTS (
      SELECT 1
      FROM teaching_assignments assignment
      WHERE assignment.id = NEW.teaching_assignment_id
        AND assignment.classroom_id = NEW.classroom_id
        AND assignment.semester_id = NEW.semester_id
        AND assignment.subject_id = NEW.subject_id
    )
    INTO assignment_matches;
    IF NOT assignment_matches THEN
      RAISE EXCEPTION 'Attendance teaching assignment does not match session scope';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_attendance_session_scope
BEFORE INSERT OR UPDATE ON attendance_sessions
FOR EACH ROW EXECUTE FUNCTION validate_attendance_session_scope();

